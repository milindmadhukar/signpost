// Command worldmap generates web/world.txt, the country shapes behind the
// Analytics page's map, and countries.go, the ISO 3166-1 name table.
//
// The shapes are Natural Earth's 1:50m admin-0 countries (public domain),
// in the Equal Earth projection, simplified and rounded so the whole map
// is a few dozen KB. Antarctica is left out, and the map is centred on
// 10°E, so the Bering Strait is the edge. Names come from the
// iso-codes package's iso_3166-1.json, with a few shorter forms.
//
// Rerun it only to change the map's look or pick up new borders:
//
//	curl -LO https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_0_countries.geojson
//	go run ./tools/worldmap -ne ne_50m_admin_0_countries.geojson -iso /usr/share/iso-codes/json/iso_3166-1.json
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"log"
	"math"
	"os"
	"sort"
	"strconv"
	"strings"
)

// Width of the map in path units. Coordinates are rounded to whole units,
// so this sets the precision: about half a CSS pixel at desktop size.
const width = 2000.0

type feature struct {
	Properties map[string]any `json:"properties"`
	Geometry   struct {
		Type        string          `json:"type"`
		Coordinates json.RawMessage `json:"coordinates"`
	} `json:"geometry"`
}

type pt struct{ x, y float64 }

func main() {
	nePath := flag.String("ne", "ne_50m_admin_0_countries.geojson", "Natural Earth admin-0 countries GeoJSON")
	isoPath := flag.String("iso", "/usr/share/iso-codes/json/iso_3166-1.json", "iso-codes iso_3166-1.json")
	outMap := flag.String("out", "web/world.txt", "map output")
	outNames := flag.String("names", "countries.go", "name table output")
	tol := flag.Float64("tolerance", 1.1, "simplification tolerance, in path units")
	minArea := flag.Float64("min-area", 6, "drop rings smaller than this (path units squared), unless it is a country's largest")
	lon0 := flag.Float64("lon0", 10, "central meridian, degrees east. Greenwich (0) leaves the Pacific islands west of the date line far from Fiji and the left edge empty")
	flag.Parse()

	var fc struct{ Features []feature }
	b, err := os.ReadFile(*nePath)
	if err != nil {
		log.Fatal(err)
	}
	if err := json.Unmarshal(b, &fc); err != nil {
		log.Fatal(err)
	}

	// Project everything first, so the crop and scale come from the land.
	type shape struct {
		code  string
		rings [][]pt
	}
	byCode := map[string]*shape{}
	var order []string
	minX, minY, maxX, maxY := math.Inf(1), math.Inf(1), math.Inf(-1), math.Inf(-1)
	for _, f := range fc.Features {
		code, _ := f.Properties["ISO_A2_EH"].(string)
		if code == "AQ" {
			continue
		}
		// Somaliland, Northern Cyprus and the Siachen Glacier have no
		// ISO code: they are drawn as land, never coloured.
		if code == "-99" || len(code) != 2 {
			code = "-"
		}
		var polys [][][][2]float64
		switch f.Geometry.Type {
		case "Polygon":
			var p [][][2]float64
			if err := json.Unmarshal(f.Geometry.Coordinates, &p); err != nil {
				log.Fatal(err)
			}
			polys = [][][][2]float64{p}
		case "MultiPolygon":
			if err := json.Unmarshal(f.Geometry.Coordinates, &polys); err != nil {
				log.Fatal(err)
			}
		default:
			continue
		}
		key := code
		if code == "-" {
			key = "-" + strconv.Itoa(len(order))
		}
		s := byCode[key]
		if s == nil {
			s = &shape{code: code}
			byCode[key] = s
			order = append(order, key)
		}
		for _, poly := range polys {
			for _, ring := range poly { // outer ring and holes alike; evenodd fill
				for _, part := range splitAtCut(ring, *lon0) {
					var r []pt
					for _, c := range part {
						p := equalEarth(c[0], c[1])
						r = append(r, p)
						minX, maxX = math.Min(minX, p.x), math.Max(maxX, p.x)
						minY, maxY = math.Min(minY, p.y), math.Max(maxY, p.y)
					}
					s.rings = append(s.rings, r)
				}
			}
		}
	}
	scale := width / (maxX - minX)
	height := math.Ceil((maxY - minY) * scale)

	var out bytes.Buffer
	fmt.Fprintf(&out, "# Generated by tools/worldmap from Natural Earth 1:50m admin-0 countries (public domain).\n")
	fmt.Fprintf(&out, "# Equal Earth projection centred on %g°E. One line per country: ISO 3166-1 alpha-2 code (or - for land with none), then an SVG path.\n", *lon0)
	fmt.Fprintf(&out, "viewBox 0 0 %d %d\n", int(width), int(height))
	sort.Strings(order)
	codes := map[string]bool{}
	for _, key := range order {
		s := byCode[key]
		var rings [][]pt
		largest, largestArea := -1, 0.0
		for i, r := range s.rings {
			for j := range r {
				r[j] = pt{(r[j].x - minX) * scale, (maxY - r[j].y) * scale}
			}
			if a := math.Abs(area(r)); a > largestArea {
				largest, largestArea = i, a
			}
		}
		for i, r := range s.rings {
			if i != largest && math.Abs(area(r)) < *minArea {
				continue
			}
			sr := round(simplify(r, *tol))
			if len(sr) < 3 {
				if i != largest {
					continue
				}
				// A microstate smaller than the rounding: a small diamond,
				// so it can still be seen and hovered.
				c := centroid(r)
				cx, cy := math.Round(c.x), math.Round(c.y)
				sr = []pt{{cx, cy - 2}, {cx + 2, cy}, {cx, cy + 2}, {cx - 2, cy}}
			}
			rings = append(rings, sr)
		}
		if len(rings) == 0 {
			continue
		}
		if s.code != "-" {
			codes[s.code] = true
		}
		fmt.Fprintf(&out, "%s %s\n", s.code, pathData(rings))
	}
	if err := os.WriteFile(*outMap, out.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("%s: %d countries, %d bytes", *outMap, len(codes), out.Len())

	if err := writeNames(*isoPath, *outNames); err != nil {
		log.Fatal(err)
	}
}

// splitAtCut re-centres a ring on lon0 and clips it at the new date line
// (lon0 - 180), returning the part on each side, each shifted into
// -180..180. Natural Earth already splits shapes at 180, so only the cut
// itself has to be handled: in the Bering Strait, Alaska and Chukotka.
func splitAtCut(ring [][2]float64, lon0 float64) [][][2]float64 {
	shifted := make([][2]float64, len(ring))
	lo, hi := math.Inf(1), math.Inf(-1)
	for i, c := range ring {
		x := c[0] - lon0 // in -180-lon0 .. 180-lon0, not yet wrapped
		shifted[i] = [2]float64{x, c[1]}
		lo, hi = math.Min(lo, x), math.Max(hi, x)
	}
	switch {
	case lo >= -180 && hi <= 180:
		return [][][2]float64{shifted}
	case hi <= -180:
		return [][][2]float64{offset(shifted, 360)}
	case lo >= 180:
		return [][][2]float64{offset(shifted, -360)}
	}
	// Straddles the cut (at -180 for lon0 > 0, at 180 for lon0 < 0).
	cut := -180.0
	if hi > 180 {
		cut = 180
	}
	var out [][][2]float64
	for _, keepAbove := range []bool{true, false} {
		part := clipLon(shifted, cut, keepAbove)
		if len(part) < 3 {
			continue
		}
		if (cut == -180) != keepAbove {
			part = offset(part, map[bool]float64{true: 360, false: -360}[cut == -180])
		}
		out = append(out, part)
	}
	return out
}

func offset(r [][2]float64, dx float64) [][2]float64 {
	out := make([][2]float64, len(r))
	for i, c := range r {
		out[i] = [2]float64{c[0] + dx, c[1]}
	}
	return out
}

// clipLon is Sutherland-Hodgman against the meridian x = cut, keeping the
// side above it (x >= cut) or below.
func clipLon(r [][2]float64, cut float64, above bool) [][2]float64 {
	in := func(c [2]float64) bool { return (c[0] >= cut) == above }
	var out [][2]float64
	for i := range r {
		cur, prev := r[i], r[(i+len(r)-1)%len(r)]
		if in(cur) != in(prev) {
			t := (cut - prev[0]) / (cur[0] - prev[0])
			out = append(out, [2]float64{cut, prev[1] + t*(cur[1]-prev[1])})
		}
		if in(cur) {
			out = append(out, cur)
		}
	}
	return out
}

// equalEarth projects longitude and latitude in degrees (Šavrič, Patterson
// and Jenny, 2018). y grows north.
func equalEarth(lon, lat float64) pt {
	const a1, a2, a3, a4 = 1.340264, -0.081106, 0.000893, 0.003796
	m := math.Sqrt(3) / 2
	l := lon * math.Pi / 180
	t := math.Asin(m * math.Sin(lat*math.Pi/180))
	t2 := t * t
	t6 := t2 * t2 * t2
	x := l * math.Cos(t) / (m * (a1 + 3*a2*t2 + t6*(7*a3+9*a4*t2)))
	y := t * (a1 + a2*t2 + t6*(a3+a4*t2))
	return pt{x, y}
}

func area(r []pt) float64 {
	s := 0.0
	for i := range r {
		j := (i + 1) % len(r)
		s += r[i].x*r[j].y - r[j].x*r[i].y
	}
	return s / 2
}

func centroid(r []pt) pt {
	var c pt
	for _, p := range r {
		c.x += p.x
		c.y += p.y
	}
	return pt{c.x / float64(len(r)), c.y / float64(len(r))}
}

// simplify is Douglas-Peucker on a closed ring.
func simplify(r []pt, tol float64) []pt {
	if len(r) > 1 && r[0] == r[len(r)-1] {
		r = r[:len(r)-1]
	}
	if len(r) < 4 {
		return r
	}
	// Split the ring at the point farthest from the first, so both halves
	// are open polylines.
	far, fd := 0, -1.0
	for i, p := range r {
		if d := math.Hypot(p.x-r[0].x, p.y-r[0].y); d > fd {
			far, fd = i, d
		}
	}
	a := dp(r[:far+1], tol)
	b := dp(append(append([]pt{}, r[far:]...), r[0]), tol)
	return append(a[:len(a)-1], b[:len(b)-1]...)
}

func dp(line []pt, tol float64) []pt {
	if len(line) < 3 {
		return line
	}
	first, last := line[0], line[len(line)-1]
	idx, maxD := 0, 0.0
	for i := 1; i < len(line)-1; i++ {
		if d := segDist(line[i], first, last); d > maxD {
			idx, maxD = i, d
		}
	}
	if maxD <= tol {
		return []pt{first, last}
	}
	l := dp(line[:idx+1], tol)
	r := dp(line[idx:], tol)
	return append(l[:len(l)-1], r...)
}

func segDist(p, a, b pt) float64 {
	dx, dy := b.x-a.x, b.y-a.y
	if dx == 0 && dy == 0 {
		return math.Hypot(p.x-a.x, p.y-a.y)
	}
	t := ((p.x-a.x)*dx + (p.y-a.y)*dy) / (dx*dx + dy*dy)
	t = math.Max(0, math.Min(1, t))
	return math.Hypot(p.x-(a.x+t*dx), p.y-(a.y+t*dy))
}

// round snaps to whole units and drops the repeats that rounding makes.
func round(r []pt) []pt {
	var out []pt
	for _, p := range r {
		q := pt{math.Round(p.x), math.Round(p.y)}
		if len(out) > 0 && out[len(out)-1] == q {
			continue
		}
		out = append(out, q)
	}
	if len(out) > 1 && out[0] == out[len(out)-1] {
		out = out[:len(out)-1]
	}
	return out
}

// pathData writes rings as absolute moves and relative lines, the shortest
// plain form: "M123 45l3-2 1 4z".
func pathData(rings [][]pt) string {
	var b strings.Builder
	for _, r := range rings {
		fmt.Fprintf(&b, "M%d %d", int(r[0].x), int(r[0].y))
		b.WriteByte('l')
		prev := r[0]
		for i, p := range r[1:] {
			dx, dy := int(p.x-prev.x), int(p.y-prev.y)
			if i > 0 && dx >= 0 {
				b.WriteByte(' ')
			}
			b.WriteString(strconv.Itoa(dx))
			if dy >= 0 {
				b.WriteByte(' ')
			}
			b.WriteString(strconv.Itoa(dy))
			prev = p
		}
		b.WriteByte('z')
	}
	return b.String()
}

// Shorter or more familiar names than iso-codes' common_name, and the
// codes Cloudflare sends that are not countries.
var nameOverrides = map[string]string{
	"BA": "Bosnia and Herzegovina", "BN": "Brunei", "BQ": "Caribbean Netherlands", "CD": "DR Congo",
	"CG": "Congo", "CI": "Côte d'Ivoire", "CZ": "Czechia", "FK": "Falkland Islands", "FM": "Micronesia",
	"GB": "United Kingdom", "HK": "Hong Kong", "KP": "North Korea", "MF": "Saint Martin", "MK": "North Macedonia",
	"MO": "Macao", "PS": "Palestine", "RU": "Russia", "SH": "Saint Helena", "SX": "Sint Maarten", "SY": "Syria",
	"TR": "Türkiye", "TW": "Taiwan", "TZ": "Tanzania", "US": "United States", "VA": "Vatican City",
	"VE": "Venezuela", "VG": "British Virgin Islands", "VI": "U.S. Virgin Islands", "VN": "Vietnam",
	"XK": "Kosovo", "T1": "Tor", "XX": "Unknown",
}

func writeNames(isoPath, outPath string) error {
	b, err := os.ReadFile(isoPath)
	if err != nil {
		return err
	}
	var iso struct {
		Entries []struct {
			A2, Name, Common string
		} `json:"3166-1"`
	}
	// iso-codes uses alpha_2 and common_name; decode through a map so the
	// struct can stay short.
	var raw map[string][]map[string]string
	if err := json.Unmarshal(b, &raw); err != nil {
		return err
	}
	for _, e := range raw["3166-1"] {
		iso.Entries = append(iso.Entries, struct{ A2, Name, Common string }{e["alpha_2"], e["name"], e["common_name"]})
	}
	names := map[string]string{}
	for _, e := range iso.Entries {
		n := e.Common
		if n == "" {
			n = e.Name
		}
		names[e.A2] = n
	}
	for k, v := range nameOverrides {
		names[k] = v
	}
	keys := make([]string, 0, len(names))
	for k := range names {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var src bytes.Buffer
	src.WriteString("// Code generated by tools/worldmap from iso-codes' ISO 3166-1 table; DO NOT EDIT.\n\npackage main\n\n")
	src.WriteString("// countries names every ISO 3166-1 alpha-2 code, plus Cloudflare's T1\n// (Tor) and XX (unknown). Codes not listed fall back to the code itself.\n")
	src.WriteString("var countries = map[string]string{\n")
	for _, k := range keys {
		fmt.Fprintf(&src, "\t%q: %q,\n", k, names[k])
	}
	src.WriteString("}\n")
	formatted, err := format.Source(src.Bytes())
	if err != nil {
		return err
	}
	log.Printf("%s: %d names", outPath, len(keys))
	return os.WriteFile(outPath, formatted, 0o644)
}
